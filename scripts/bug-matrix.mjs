// Detection matrix: switches on ONE seeded defect at a time, runs the whole suite, and records which tests fail.
// Usage: npm run bug-matrix        (takes several minutes; needs the database running)
// Writes: docs/SEEDED-BUGS.md
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

// The defect names and descriptions come from app/bugs.ts, the single source of truth.
const source = readFileSync('app/bugs.ts', 'utf8');
const bugs = [...source.matchAll(/^\s+'([a-z-]+)',\s*\/\/\s*(.*)$/gm)].map(([, name, description]) => ({ name, description }));
if (bugs.length === 0) throw new Error('No bugs found in app/bugs.ts');

const idOf = (title) => /^([A-Z0-9]+(?:-[A-Z]+)*-\d{3}):/.exec(title)?.[1] ?? title.slice(0, 40);

/** Runs some Playwright projects with the given defect on and returns the parsed JSON report. */
function playwright(bugName, args) {
  const result = spawnSync('npx', ['playwright', 'test', '--reporter=json', ...args], {
    shell: true,
    encoding: 'utf8',
    maxBuffer: 1 << 29,
    env: { ...process.env, BUGS: bugName },
  });
  const out = result.stdout ?? '';
  return JSON.parse(out.slice(out.indexOf('{'), out.lastIndexOf('}') + 1));
}

function runSuite(bugName) {
  const started = Date.now();
  // Start every run from the same clean data: an earlier defect (for example "stock-not-decreased")
  // can leave wrong stock numbers behind, and that must not leak into the next run.
  spawnSync('npm', ['run', 'db:reset'], { shell: true, encoding: 'utf8' });

  // The "isolated" stock tests are skipped by Playwright when a project they depend on fails, which is exactly
  // what happens when a defect is caught. So they are run separately, on their own, with --no-deps.
  const reports = [
    playwright(bugName, ['--project=ui', '--project=e2e', '--project=api', '--project=database']),
    playwright(bugName, ['--project=isolated', '--no-deps']),
  ];
  const collect = (reportList) => {
    const failed = [];
    let total = 0;
    const walk = (suite) => {
      for (const spec of suite.specs ?? []) {
        total += 1;
        if (!spec.ok) failed.push(idOf(spec.title));
      }
      for (const child of suite.suites ?? []) walk(child);
    };
    reportList.forEach((report) => report.suites.forEach(walk));
    return { total, failed: [...new Set(failed)].sort() };
  };

  const first = collect(reports);
  let failed = first.failed;
  if (failed.length > 0) {
    // Confirmation run: a test only counts as "caught the defect" if it fails AGAIN when run on its own.
    // This filters out one-off failures caused by timing or machine load, which are not caused by the defect.
    spawnSync('npm', ['run', 'db:reset'], { shell: true, encoding: 'utf8' });
    const pattern = `"${failed.join('|')}"`;
    const again = playwright(bugName, [
      '--project=ui', '--project=e2e', '--project=api', '--project=database', '--project=isolated',
      '--no-deps', '--grep', pattern,
    ]);
    failed = collect([again]).failed;
  }
  return { total: first.total, failed, firstPassFailures: first.failed.length, seconds: Math.round((Date.now() - started) / 1000) };
}

const rows = [];
console.log('Control run: no defects switched on');
const control = runSuite('');
console.log(`  ${control.total} tests, ${control.failed.length} failed (${control.seconds}s)`);
for (const bug of bugs) {
  console.log(`Defect: ${bug.name}`);
  const run = runSuite(bug.name);
  console.log(`  ${run.failed.length} test(s) failed: ${run.failed.join(', ') || 'NONE: not detected!'}`);
  rows.push({ ...bug, ...run });
}

const detected = rows.filter((r) => r.failed.length > 0).length;
const lines = [
  '# Seeded defects and the tests that catch them',
  '',
  `Generated by \`npm run bug-matrix\` on ${new Date().toISOString().slice(0, 10)}.`,
  `Control run (no defects): **${control.total} tests, ${control.failed.length} failed**.`,
  `Each defect below was switched on alone (\`BUGS=<name>\`) and the whole suite was run: **${detected} of ${rows.length} defects were detected.**`,
  'A test is listed only if it failed in the full run AND failed again when re-run on its own with the defect still on',
  '(this removes one-off failures caused by machine load, which the defect did not cause).',
  '',
  '| Defect | What it does | Tests that failed | Test IDs |',
  '|---|---|---|---|',
  ...rows.map(
    (r) =>
      `| \`${r.name}\` | ${r.description} | ${r.failed.length} | ${r.failed.length ? r.failed.join(', ') : '**not detected**'} |`,
  ),
  '',
  'To try one yourself: `npx cross-env BUGS=sort-price-reversed npx playwright test --project=ui`, or switch all on',
  'with `npm run test:bugs` (its report is written to `reports/html-bugs`; open it with `npm run report:bugs`).',
  '',
];
writeFileSync('docs/SEEDED-BUGS.md', lines.join('\n'));
console.log(`\nWrote docs/SEEDED-BUGS.md: ${detected} of ${rows.length} defects detected.`);
if (control.failed.length > 0 || detected < rows.length) process.exitCode = 1;
