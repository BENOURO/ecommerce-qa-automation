// Builds docs/TEST-CASES.md from the real test titles (reports/results.json is NOT needed: titles are read from the code)
// plus the hand-written details in docs/test-case-details.mjs.
// Usage: npm run docs:tests          (writes the file)
//        npm run docs:check          (fails if a test has no documentation, or documentation has no test)
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { details, preconditionsByPrefix } from '../docs/test-case-details.mjs';

const checkOnly = process.argv.includes('--check');

function specFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? specFiles(path) : path.endsWith('.spec.ts') ? [path] : [];
  });
}

// A test title looks like  test('AUTH-API-001: description', ...)  or a template string with the same shape.
const tests = new Map();
for (const file of specFiles('tests')) {
  const layer = file.split(/[\\/]/)[1];
  for (const match of readFileSync(file, 'utf8').matchAll(/test\(\s*[`'"]([A-Z0-9]+(?:-[A-Z]+)*-\d{3}):\s*(.+?)[`'"],\s*async/g)) {
    const [, id, title] = match;
    if (!tests.has(id)) tests.set(id, { title: title.replace(/\$\{[^}]*\}/g, '…'), layer });
  }
}

const missingDocs = [...tests.keys()].filter((id) => !details[id]);
const missingTests = Object.keys(details).filter((id) => !tests.has(id));
if (missingDocs.length || missingTests.length) {
  if (missingDocs.length) console.error(`Tests without documentation: ${missingDocs.join(', ')}`);
  if (missingTests.length) console.error(`Documentation without a test: ${missingTests.join(', ')}`);
  process.exit(1);
}
if (checkOnly) {
  console.log(`OK: ${tests.size} test cases are documented and every documented case has a test.`);
  process.exit(0);
}

const areas = [
  ['SMK-', 'Smoke tests'],
  ['AUTH-', 'Authentication'],
  ['PROD-', 'Products'],
  ['CART-', 'Shopping cart'],
  ['CHK-', 'Checkout'],
  ['DB-USR', 'Database: users'],
  ['DB-PRD', 'Database: products'],
  ['DB-ORD', 'Database: orders and order items'],
  ['E2E-', 'End-to-end journeys (UI, API and database)'],
  ['STK-', 'Stock handling (isolated)'],
];
const preconditionFor = (id) =>
  preconditionsByPrefix[Object.keys(preconditionsByPrefix).find((p) => id.startsWith(p) && (id.startsWith('DB-') ? id.startsWith(p) : true)) ?? ''] ?? '';
const layerName = { ui: 'UI', api: 'API', database: 'DB', e2e: 'E2E', isolated: 'DB+API' };
const esc = (text) => text.replace(/\|/g, '\\|');

const lines = [
  '# Test case documentation',
  '',
  `${tests.size} test cases (some run with several data sets, so the suite executes more tests than this list has rows).`,
  'Generated by `npm run docs:tests` from the test code and `docs/test-case-details.mjs`; `npm run docs:check` verifies they match.',
  '',
  '**Priority:** P1 = critical (money, security, data integrity), P2 = high, P3 = medium (edge cases, polish).',
  '',
  '| Area | Cases | P1 | P2 | P3 |',
  '|---|---|---|---|---|',
];
const groups = areas.map(([prefix, title]) => ({
  title,
  ids: [...tests.keys()].filter((id) => id.startsWith(prefix)).sort(),
}));
for (const group of groups) {
  const count = (p) => group.ids.filter((id) => details[id][0] === p).length;
  lines.push(`| ${group.title} | ${group.ids.length} | ${count('P1')} | ${count('P2')} | ${count('P3')} |`);
}
lines.push('');

for (const group of groups) {
  lines.push(`## ${group.title}`, '');
  lines.push(`**Preconditions:** ${preconditionFor(group.ids[0])}`, '');
  lines.push('| ID | Layer | Priority | Description | Execution steps | Expected result |', '|---|---|---|---|---|---|');
  for (const id of group.ids) {
    const [priority, steps, expected] = details[id];
    lines.push(`| ${id} | ${layerName[tests.get(id).layer]} | ${priority} | ${esc(tests.get(id).title)} | ${esc(steps)} | ${esc(expected)} |`);
  }
  lines.push('');
}
writeFileSync('docs/TEST-CASES.md', lines.join('\n'));
console.log(`Wrote docs/TEST-CASES.md with ${tests.size} test cases.`);
